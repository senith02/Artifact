"""Time from the advisor Action's first step to its recorded decision, from the real P4-T2 CI runs.

Reads results/p4/demo_runs/combined_audit.jsonl (the audit records the seven demo runs uploaded) and
reports, per record, ``audit_ts - inputs.arrival_utc``. ``arrival_utc`` is the UTC clock read by the
Action's first step (action.yml `clock`, whole-second resolution); ``audit_ts`` is written when the
advisor appends its audit record. The interval therefore includes setup-python, installing the pinned
dependency subset, loading the frozen core, the GitHub history fetch, decide() and the live-intensity
fetch: it is an upper bound on the advisor's own response time, not a measurement of decide() alone.

Run from code/:  python scripts/advisor_step_latency.py
Writes results/p4/demo_runs/step_latency.{json,md}. Reads nothing else; computes nothing else.
"""

from __future__ import annotations

import json
import statistics
from datetime import datetime
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
RUNS = ROOT / "results" / "p4" / "demo_runs"


def _ts(s: str) -> datetime:
    return datetime.fromisoformat(s.replace("Z", "+00:00"))


def main() -> None:
    rows = []
    with open(RUNS / "combined_audit.jsonl", encoding="utf-8") as fh:
        for line in fh:
            if not line.strip():
                continue
            r = json.loads(line)
            seconds = (_ts(r["audit_ts"]) - _ts(r["inputs"]["arrival_utc"])).total_seconds()
            rows.append({"run_id": r["inputs"]["run_id"], "branch": r["inputs"]["branch"],
                         "event": r["inputs"]["event"], "scenario": r.get("scenario"),
                         "display": r["display"], "seconds": round(seconds, 2)})
    secs = [r["seconds"] for r in rows]
    summary = {"command": "python scripts/advisor_step_latency.py",
               "source": "results/p4/demo_runs/combined_audit.jsonl",
               "measure": "audit_ts - inputs.arrival_utc (first Action step to recorded decision), seconds",
               "includes": "setup-python, pinned dependency install, frozen-core load, GitHub history fetch, "
                           "decide(), live-intensity fetch; arrival_utc has whole-second resolution",
               "n_records": len(secs), "min_s": min(secs), "median_s": statistics.median(secs),
               "max_s": max(secs), "records": rows}
    (RUNS / "step_latency.json").write_text(json.dumps(summary, indent=2) + "\n", encoding="utf-8")
    md = ["# Advisor step latency (P4-T2 demo runs)", "",
          f"> Generated by `{summary['command']}` from `{summary['source']}`.", "",
          f"Measure: {summary['measure']}. Includes {summary['includes']}. An upper bound on the advisor's "
          "response time, not a timing of `decide()` alone.", "",
          f"**{len(secs)} records: min {min(secs):.2f} s, median {statistics.median(secs):.2f} s, "
          f"max {max(secs):.2f} s.**", "",
          "| run | event | branch | scenario | decision | seconds |", "| --: | :-- | :-- | :-- | :-- | --: |"]
    md += [f"| {r['run_id']} | {r['event']} | `{r['branch']}` | {r['scenario'] or '—'} | {r['display']} | "
           f"{r['seconds']:.2f} |" for r in rows]
    (RUNS / "step_latency.md").write_text("\n".join(md) + "\n", encoding="utf-8")
    print(f"{len(secs)} records: min {min(secs):.2f} s, median {statistics.median(secs):.2f} s, "
          f"max {max(secs):.2f} s")


if __name__ == "__main__":
    main()
